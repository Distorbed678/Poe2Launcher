//! Embeds every version file in `../versions/` (the copies of the main repository's
//! `versions/<version>.toml`, kept by `cargo xtask versions`; docs/guides/new-game-version.md)
//! into `EMBEDDED_VERSIONS`, oldest first by `build_revision`, so adding a build is adding a
//! file. `depotdownloader.toml` and anything else without a `build_revision` is skipped.

use std::{env, fs, path::PathBuf};

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../versions");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut found: Vec<(u64, String, PathBuf)> = Vec::new();
    for entry in fs::read_dir(&dir).expect("versions/ folder").flatten() {
        let path = entry.path();
        if path.extension().is_none_or(|e| e != "toml") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", path.display());
        let text = fs::read_to_string(&path).expect("readable version file");
        let revision = text.lines().find_map(|l| {
            let (key, value) = l.split_once('=')?;
            (key.trim() == "build_revision").then(|| value.trim().trim_matches('"').parse::<u64>().ok())?
        });
        let version = text.lines().find_map(|l| {
            let (key, value) = l.split_once('=')?;
            (key.trim() == "version").then(|| value.trim().trim_matches('"').to_owned())
        });
        if let (Some(revision), Some(version)) = (revision, version) {
            found.push((revision, version, path.canonicalize().expect("canonical path")));
        }
    }
    found.sort();
    let mut out = String::from("/// Generated by build.rs from versions/*.toml.\nconst EMBEDDED_VERSIONS: &[(&str, &str)] = &[\n");
    for (_, version, path) in &found {
        out.push_str(&format!("    ({version:?}, include_str!({:?})),\n", path.display().to_string()));
    }
    out.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("embedded_versions.rs"), out).unwrap();
    tauri_build::build()
}
